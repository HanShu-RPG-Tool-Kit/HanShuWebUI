import assert from 'node:assert/strict'
import {readFile} from 'node:fs/promises'
import {join} from 'node:path'
import {chromium} from 'playwright'
import {harness} from './collaboration-harness.mjs'
import {loginProject} from './project-ui-helpers.mjs'
import {until} from './progress-collaboration-helpers.mjs'
const h=await harness(true);let browser
try{
 const owner=await h.login(h.credential,'smoke owner')
 const account=await h.api(owner.token,'/api/subjects','POST',{name:'Editor',kind:'human',role:'editor'})
 await h.commit(owner.token,[{path:'src/bossbars/demo.bossbar',content:'{}'},{path:'meta/explorer.json',content:JSON.stringify({version:1,folders:[{key:'shared-folder',name:'共享章节',package:'quest',parentId:null}],placements:{}})}]);await h.release(owner.token)
 browser=await chromium.launch({headless:true,...process.platform==='win32'?{channel:'msedge'}:{}})
 const page=await (await browser.newContext()).newPage()
 const errors=[];page.on('pageerror',e=>errors.push(String(e)))
 await loginProject(page,h.base,account.credential,'smoke')
 await page.getByRole('tab',{name:'剧本',exact:true}).click()
 const pane=page.locator('.app-workspace-pane.active')
 const sp=pane.locator('.stageplay-explorer.explorer-shell')
 await sp.getByText('汉书剧本',{exact:true}).first().waitFor()
 assert.equal(await sp.locator('.stageplay-explorer-project').count(),0,'project name must not occupy the category tree')
 assert.equal(await pane.getByRole('button',{name:'+包',exact:true}).count(),0)
 assert.equal(await pane.locator('button[title="删除包"]').count(),0)
 assert.equal(await sp.getByRole('button',{name:'+剧',exact:true}).count(),1)
 await sp.locator('.explorer-assets-row').filter({hasText:'assets'}).first().waitFor()
 await sp.locator('.explorer-shell-tree').click({button:'right'})
 assert.equal(await page.getByRole('menuitem',{name:'重命名工程'}).count(),0)
 assert.equal(await page.getByRole('menuitem',{name:'删除',exact:true}).count(),0)
 await page.keyboard.press('Escape')
 console.log('PASS stageplay: category tree without project row, no package UI, assets addon mounted')
 const readMeta=async()=>JSON.parse(await readFile(join(h.root,'meta/explorer.json'),'utf8'))
 await sp.locator('[role=treeitem][title="汉书剧本"]').click({button:'right'})
 await page.getByRole('menuitem',{name:'新建文件夹',exact:true}).click()
 const spFolder=sp.getByRole('textbox',{name:'新文件夹名称',exact:true});await spFolder.fill('第一章');await spFolder.press('Enter')
 await until(async()=>{const m=await readMeta();return m.version===2&&m.folders.some(f=>f.name==='第一章'&&f.category==='hanshu')&&m.folders.some(f=>f.name==='共享章节'&&f.category==='quest')},'stageplay folder not committed as v2 alongside gameplay folder')
 const chapter=sp.locator('[role=treeitem][title="第一章"]');await chapter.waitFor()
 assert.equal((await h.files(owner.token)).entries.some(e=>e.path.includes('第一章')),false,'virtual folder must not create a disk directory')
 console.log('PASS stageplay: shared virtual folder committed through S as v2, gameplay folder preserved')
 await chapter.click({button:'right'})
 await page.getByRole('menuitem',{name:'新建汉书剧本',exact:true}).click()
 const createdName=sp.getByRole('textbox',{name:'重命名资源',exact:true});await createdName.waitFor()
 await createdName.press('Escape')
 await until(async()=>{const m=await readMeta();const key=m.folders.find(f=>f.name==='第一章')?.key;return Object.entries(m.placements).some(([path,folder])=>path.startsWith('src/hanshu/')&&folder===key)},'new stageplay file was not placed into the target folder')
 assert.equal(Number(await sp.locator('[role=treeitem].selected').getAttribute('aria-level')),Number(await chapter.getAttribute('aria-level'))+1)
 console.log('PASS stageplay: new file created inside a virtual folder keeps its canonical path and shared placement')
 await page.getByRole('tab',{name:'游戏性',exact:true}).click()
 await pane.locator('[role=treeitem][title="共享章节"]').waitFor()
 console.log('PASS gameplay: legacy v1 folder read through shell rows')
 await page.getByRole('tab',{name:'视听效果',exact:true}).click()
 const av=pane.locator('.explorer-shell')
 await av.getByText('BOSS血条',{exact:true}).first().waitFor()
 await av.getByText('demo.bossbar').first().waitFor()
 await av.getByText('BOSS血条',{exact:true}).first().click({button:'right'})
 const mk=page.getByRole('menuitem',{name:'新建文件夹',exact:true});await mk.waitFor();await mk.click()
 const input=av.locator('input').last();await input.fill('血条组');await input.press('Enter')
 await until(async()=>{const m=JSON.parse(await readFile(join(h.root,'meta/explorer.json'),'utf8'));return m.version===2&&m.folders.some(f=>f.name==='血条组'&&f.category==='bossbar')&&m.folders.some(f=>f.name==='共享章节'&&f.category==='quest')&&m.folders.some(f=>f.name==='第一章'&&f.category==='hanshu')},'AV folder not committed as v2 alongside gameplay and stageplay folders')
 console.log('PASS audiovisual: shared folder committed through S as v2, gameplay and stageplay folders preserved')
 assert.deepEqual(errors,[])
}finally{await browser?.close();await h.stop()}