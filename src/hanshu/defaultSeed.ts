/**
 * 新建 `.hs` / 新工程默认剧本。
 * 须符合当前语法（见帮助「.hs 语法说明」）；不要写中文 speaker、裸「标题：」或未加 `#` 的场景行。
 */
export function defaultHsSeed(title = '新剧本'): string {
  const name = title.trim() || '新剧本'
  return [
    `# ${name}`,
    '',
    '#【场景】在此填写场景提示',
    '',
    'narrator:',
    '在这里写下旁白。',
    '对白块以单独一行 // 结束；选项写在对白块外。',
    '//',
    '',
    '-继续往前:巷子深处有灯火。//',
    '-先观望一会:雨声渐渐大了。//',
    '',
  ].join('\n')
}
